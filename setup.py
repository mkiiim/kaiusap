"""Build the native hook entry point; the core remains a Python package."""
import os
from pathlib import Path
import re
import subprocess

from setuptools import setup
from setuptools.command.bdist_wheel import bdist_wheel
from distutils.command.build_scripts import build_scripts
from setuptools.command.build_py import build_py
import json

PARTS = Path('src/kaiusap/adapters')


def literal(path):
    """A Rust string literal for a path."""
    text = str(path)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def registry(parts):
    """The engine's table of provider parts: a `#[path]` module per `<p>.rs` and `PARTS`."""
    lines = ['// Generated by setup.py from src/kaiusap/adapters/*.rs at build time. Not committed.']
    for part in parts:
        lines.append(f'#[path = {literal(part.resolve())}]\nmod {part.stem};')
    entries = ''.join(f'\n    ({literal(part.stem)}, &{part.stem}::Native),' for part in parts)
    lines.append(f'const PARTS: &[(&str, &dyn Provider)] = &[{entries}\n];')
    return '\n'.join(lines) + '\n'


def parts():
    found = sorted(PARTS.glob('*.rs'))
    for part in found:
        if not re.fullmatch(r'[a-z][a-z0-9_]*', part.stem):
            raise SystemExit(f'{part}: a native part is named after its provider, in lowercase')
    return found


def rustc(build_temp, *arguments):
    """Compile the engine with every provider part found, as the install does."""
    generated = Path(build_temp) / 'kaiusap-native-parts.rs'
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text(registry(parts()))
    subprocess.run(['rustc', '--edition=2021', *arguments, 'native/hook.rs'], check=True,
                   env={**os.environ, 'KAIUSAP_PARTS': str(generated.resolve())})


def git(*arguments):
    """One git command's output in this source tree, or None when git or the repository isn't there."""
    try:
        done = subprocess.run(['git', *arguments], capture_output=True, text=True, timeout=10,
                              cwd=Path(__file__).resolve().parent)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return done.stdout.strip() if done.returncode == 0 else None


def build_record():
    """What `version` reports: the commit built, its date and whether what the build packages differs from it: a
    change, or a file git doesn't track, in a path the package is built from."""
    commit = git('rev-parse', 'HEAD')
    if not commit:
        return {'commit': None, 'commit_date': None, 'dirty': None}
    status = git('status', '--porcelain', '--untracked-files=all', '--',
                 'src', 'native', 'scripts', 'setup.py', 'pyproject.toml', 'MANIFEST.in')
    return {'commit': commit, 'commit_date': git('log', '-1', '--format=%cI'),
            'dirty': None if status is None else bool(status)}


class BuildPy(build_py):
    def run(self):
        super().run()
        target = Path(self.build_lib) / 'kaiusap' / 'build.json'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(build_record()) + '\n')


class BuildScripts(build_scripts):
    def run(self):
        Path(self.build_dir).mkdir(parents=True, exist_ok=True)
        target = str(Path(self.build_dir) / 'kaiusap')
        rustc(self.get_finalized_command('build').build_temp,
              '-C', 'opt-level=3', '-C', 'strip=symbols', '-o', target)
        self.outfiles = [target]

    def get_outputs(self):
        return self.outfiles


class PlatformWheel(bdist_wheel):
    def finalize_options(self):
        super().finalize_options()
        self.root_is_pure = False

    def get_tag(self):
        _, _, platform = super().get_tag()
        return 'py3', 'none', platform


if __name__ == '__main__':
    setup(scripts=['scripts/kaiusap'], cmdclass={'build_py': BuildPy, 'build_scripts': BuildScripts, 'bdist_wheel': PlatformWheel})
